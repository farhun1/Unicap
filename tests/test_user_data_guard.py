"""Subscriber-data guard: NO capture file may ever enter git, in any directory.

Captures hold subscriber data (IMSI/MSISDN, private IPs, operator addressing), so
the rule is blanket: every capture format is gitignored everywhere, the tests'
own fixture is generated at run time instead of committed, and a pre-commit hook
refuses a capture even after `git add -f`.

These tests lock that in so a later .gitignore edit cannot silently make captures
publishable. They also exercise the hook in a throwaway repository.
"""

import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

import pcapgen

REPO = Path(__file__).parents[1]
GIT = shutil.which("git")
HOOK = REPO / ".githooks" / "pre-commit"

pytestmark = pytest.mark.skipif(
    GIT is None or not (REPO / ".git").exists(),
    reason="needs a git checkout with git on PATH",
)

# Capture formats tshark reads (plus gzip, which this app accepts).
CAPTURE_EXTS = (".pcap", ".pcapng", ".cap", ".dmp", ".snoop", ".erf", ".gz")

# tests/fixtures/gtpv2_csr.pcap was committed before this rule existed. It is a
# 120-byte synthetic capture generated by tests/pcapgen.py (no user data) and is
# no longer tracked; removing it from published history needs a rewrite we
# deliberately do not do here. Anything else in history is a real failure.
GRANDFATHERED = {"tests/fixtures/gtpv2_csr.pcap"}


def git(*args, cwd=REPO):
    return subprocess.run([GIT, "-C", str(cwd), *args], capture_output=True, text=True)


def is_ignored(path: str) -> bool:
    # --no-index asks about the rules alone, whether or not the file exists or is tracked
    return git("check-ignore", "--no-index", "--quiet", "--", path).returncode == 0


def is_capture(path: str) -> bool:
    if path.startswith("samples/") and path != "samples/README.md":
        return True
    return path.lower().endswith(CAPTURE_EXTS)


@pytest.mark.parametrize("path", [
    # no capture anywhere, not just under samples/
    "capture.pcap",
    "capture.pcapng",
    "capture.cap",
    "trace.dmp",
    "trace.snoop",
    "trace.erf",
    "trace.gz",
    "docs/example.pcap",
    "tests/fixtures/capture.pcap",
    "tests/fixtures/gtpv2_csr.pcap",
    "src/unipcap/x.pcapng",
    "some/nested/dir/trace.pcap",
    # samples/ keeps its extra non-capture data local too
    "samples/capture.pcap",
    "samples/capture.pcap.gz",
    "samples/capture.expected.json",
    "samples/CMDTJ (2).pcap",
    "samples/Sample_SM/RecordQueryFlowChart_1/pcap/export_ETHERNET.pcap",
    "samples/Some Folder/trace.pcapng",
])
def test_captures_are_never_committable(path):
    assert is_ignored(path), f"{path} would be committed; captures can hold subscriber data"


def test_samples_readme_stays_trackable():
    # the only file under samples/ that may ship
    assert not is_ignored("samples/README.md")


def test_no_capture_is_tracked():
    offenders = sorted(p for p in git("ls-files").stdout.splitlines() if is_capture(p))
    assert not offenders, f"capture data is tracked: {offenders}"


def test_no_new_capture_in_history():
    added = git("log", "--all", "--pretty=format:", "--name-only", "--diff-filter=A").stdout
    offenders = sorted({p for p in added.splitlines() if is_capture(p)} - GRANDFATHERED)
    assert not offenders, f"capture data is in git history: {offenders}"


def test_test_fixture_is_generated_not_committed():
    tracked = git("ls-files", pcapgen.FIXTURE_NAME).stdout.splitlines()
    assert not tracked, "the capture fixture must not be tracked; generate it at test time"
    rebuilt = pcapgen.ensure_gtpv2_csr_fixture(
        Path(tempfile.mkdtemp()) / pcapgen.FIXTURE_NAME)
    assert rebuilt.read_bytes()[:4] == b"\xd4\xc3\xb2\xa1", "fixture must be a real pcap"


def _find_shell():
    for name in ("sh", "bash"):
        found = shutil.which(name)
        if found:
            return found
    # Windows: Git ships sh next to the git executable but not on PATH
    git_dir = Path(GIT).resolve().parent.parent
    for rel in ("bin/sh.exe", "usr/bin/sh.exe", "bin/sh", "usr/bin/sh"):
        if (git_dir / rel).is_file():
            return str(git_dir / rel)
    return None


def test_pre_commit_hook_blocks_captures_anywhere(tmp_path):
    shell = _find_shell()
    if shell is None:
        pytest.skip("needs a POSIX shell (Git's sh/bash) to run hooks")
    assert HOOK.is_file(), "the pre-commit guard is missing"
    assert b"\r\n" not in HOOK.read_bytes(), "CRLF shebang would break the hook under sh"
    git("init", "-q", cwd=tmp_path)
    (tmp_path / "samples").mkdir()
    (tmp_path / "samples" / "README.md").write_text("keep me\n", encoding="utf-8")
    (tmp_path / "tests" / "fixtures").mkdir(parents=True)
    (tmp_path / ".githooks").mkdir()
    shutil.copy2(HOOK, tmp_path / ".githooks" / "pre-commit")
    hook = str(tmp_path / ".githooks" / "pre-commit")

    def run():
        return subprocess.run([shell, hook], cwd=tmp_path, capture_output=True, text=True)

    # ordinary files and the samples README are allowed
    (tmp_path / "notes.txt").write_text("x\n", encoding="utf-8")
    git("add", "notes.txt", "samples/README.md", cwd=tmp_path)
    assert run().returncode == 0

    # a force-added capture is refused wherever it sits
    for rel in ("samples/real.pcap", "trace.pcapng", "tests/fixtures/probe.cap",
                "docs/dump.gz"):
        probe = tmp_path / rel
        probe.parent.mkdir(parents=True, exist_ok=True)
        probe.write_bytes(b"\xd4\xc3\xb2\xa1")
        git("add", "-f", rel, cwd=tmp_path)
        result = run()
        assert result.returncode == 1, f"{rel} was not blocked"
        assert rel in result.stderr
